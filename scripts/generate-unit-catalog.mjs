/**
 * Builds docs/units/: one markdown catalog per faction, listing every unit
 * that ships a usable animation set, with a thumbnail of its idle frame.
 *
 * Usage: npm run unit-catalog
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const __dirname = dirname(fileURLToPath(import.meta.url));
const UNITS_DIR = join(__dirname, '..', 'public', 'resources', 'units');
const DOCS_DIR = join(__dirname, '..', 'docs', 'units');
const THUMBS_DIR = join(DOCS_DIR, 'thumbs');
const THUMB_SIZE = 96;

/** Minimum animation set a unit must expose to be listed. */
const REQUIRED_ANIMS = ['idle', 'attack', 'death'];

/** Duelyst faction prefixes → display names. */
const FACTIONS = [
    { key: 'f1', slug: 'lyonar', label: 'Lyonar Kingdoms' },
    { key: 'f2', slug: 'songhai', label: 'Songhai Empire' },
    { key: 'f3', slug: 'vetruvian', label: 'Vetruvian Imperium' },
    { key: 'f4', slug: 'abyssian', label: 'Abyssian Host' },
    { key: 'f5', slug: 'magmar', label: 'Magmar Aspects' },
    { key: 'f6', slug: 'vanar', label: 'Vanar Kindred' },
    { key: 'neutral', slug: 'neutral', label: 'Neutral' },
    { key: 'boss', slug: 'boss', label: 'Bosses' },
];
const MISC = { key: 'misc', slug: 'misc', label: 'Misc (critters, props)' };

/** Animation aliases used inconsistently across the source atlases. */
const ALIASES = { hurt: 'hit', breath: 'breathing', breathe: 'breathing', crawl: 'run' };

function parseAtlas(unit) {
    const atlas = JSON.parse(readFileSync(join(UNITS_DIR, `${unit}_atlas.json`), 'utf8'));
    const anims = new Map();
    for (const [name, entry] of Object.entries(atlas.frames)) {
        const raw = name.slice(unit.length + 1).replace(/_\d+$/, '');
        const anim = ALIASES[raw] ?? raw;
        if (!anims.has(anim)) anims.set(anim, []);
        anims.get(anim).push(entry.frame);
    }
    return anims;
}

/** Preview candidates, best pose first. Some early frames are blank, hence a list. */
function previewCandidates(anims) {
    const out = [];
    for (const anim of ['idle', 'breathing', 'run', 'attack']) {
        out.push(...(anims.get(anim) ?? []));
    }
    return out;
}

/** `trim()` throws on a fully transparent frame — that is our blank-frame filter. */
async function writeThumb(unit, candidates) {
    const src = sharp(join(UNITS_DIR, `${unit}.png`));
    for (const frame of candidates) {
        try {
            await src
                .clone()
                .extract({ left: frame.x, top: frame.y, width: frame.w, height: frame.h })
                .trim()
                .resize(THUMB_SIZE, THUMB_SIZE, {
                    fit: 'contain',
                    background: { r: 0, g: 0, b: 0, alpha: 0 },
                })
                .png()
                .toFile(join(THUMBS_DIR, `${unit}.png`));
            return true;
        } catch {
            // blank or out-of-bounds frame — try the next pose
        }
    }
    return false;
}

function factionOf(unit) {
    return FACTIONS.find((f) => unit.startsWith(`${f.key}_`)) ?? MISC;
}

function prettyName(unit, factionKey) {
    const bare = unit.startsWith(`${factionKey}_`) ? unit.slice(factionKey.length + 1) : unit;
    return bare.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

function markdown(faction, units) {
    const lines = [
        `# ${faction.label}`,
        '',
        `${units.length} units with a complete animation set (\`${REQUIRED_ANIMS.join('`, `')}\`).`,
        '',
        'Sprites: `public/resources/units/{id}.png` + `{id}_atlas.json` (CC0, open-duelyst).',
        '',
        '| Sprite | Name | Id | Animations |',
        '| --- | --- | --- | --- |',
    ];
    for (const u of units) {
        const anims = [...u.anims.entries()]
            .sort(([a], [b]) => a.localeCompare(b))
            .map(([name, frames]) => `${name} (${frames.length})`)
            .join(', ');
        lines.push(`| ![${u.id}](thumbs/${u.id}.png) | ${u.name} | \`${u.id}\` | ${anims} |`);
    }
    lines.push('');
    return lines.join('\n');
}

function indexMarkdown(groups, skipped) {
    const lines = [
        '# Unit Sprite Catalog',
        '',
        'Generated by `npm run unit-catalog`. Do not edit by hand.',
        '',
        'Only units exposing the full core animation set are listed ' +
            `(\`${REQUIRED_ANIMS.join('`, `')}\`).`,
        '',
        '| Faction | Units | Catalog |',
        '| --- | --- | --- |',
    ];
    let total = 0;
    for (const [faction, units] of groups) {
        total += units.length;
        lines.push(`| ${faction.label} | ${units.length} | [${faction.slug}.md](${faction.slug}.md) |`);
    }
    lines.push(`| **Total** | **${total}** | |`, '');
    if (skipped.length) {
        lines.push(
            '## Skipped',
            '',
            `${skipped.length} sprites lack part of the core set:`,
            '',
            ...skipped.map((s) => `- \`${s.id}\` — missing ${s.missing.join(', ')}`),
            ''
        );
    }
    return lines.join('\n');
}

const ids = readdirSync(UNITS_DIR)
    .filter((f) => f.endsWith('_atlas.json'))
    .map((f) => f.slice(0, -'_atlas.json'.length))
    .sort();

rmSync(THUMBS_DIR, { recursive: true, force: true });
mkdirSync(THUMBS_DIR, { recursive: true });

const groups = new Map(FACTIONS.concat(MISC).map((f) => [f, []]));
const skipped = [];

for (const id of ids) {
    const anims = parseAtlas(id);
    const missing = REQUIRED_ANIMS.filter((a) => !anims.has(a));
    if (missing.length) {
        skipped.push({ id, missing });
        continue;
    }
    if (!(await writeThumb(id, previewCandidates(anims)))) {
        skipped.push({ id, missing: ['no renderable preview frame'] });
        continue;
    }
    const faction = factionOf(id);
    groups.get(faction).push({ id, name: prettyName(id, faction.key), anims });
}

for (const [faction, units] of groups) {
    if (!units.length) continue;
    writeFileSync(join(DOCS_DIR, `${faction.slug}.md`), markdown(faction, units));
}

const nonEmpty = [...groups].filter(([, units]) => units.length);
writeFileSync(join(DOCS_DIR, 'README.md'), indexMarkdown(nonEmpty, skipped));

console.log(
    `${ids.length - skipped.length} units catalogued across ${nonEmpty.length} factions, ${skipped.length} skipped.`
);
